/**
 * Proposed Web Pixel attribution -> verified order boundary.
 *
 * This module is PURE and DOES NOT call Shopify, send a postback, persist data,
 * or credit a creator. Do not use its output to create affiliate_orders.
 *
 * A trusted server must independently fetch the Shopify order and supply it to
 * assessVerifiedAttribution; a browser-supplied order object is never proof.
 */
const SHOP_RE = /^[a-z0-9][a-z0-9-]*\.myshopify\.com$/;
const CLICK_ID_RE = /^[A-Za-z0-9_-]{8,128}$/;
const ORDER_RE = /^(?:gid:\/\/shopify\/Order\/)?([1-9][0-9]{0,19})$/;
const MAX_WINDOW_MS = 30 * 24 * 60 * 60 * 1000;

export function normalizeShopifyOrderId(value) {
  if (typeof value !== "string" && typeof value !== "number") return null;
  const match = String(value).match(ORDER_RE);
  return match ? match[1] : null;
}

/**
 * @param {object} input
 * @param {object} input.candidate - proposal generated by proposeAttributionCandidate.
 * @param {object} input.verifiedOrder - response obtained server-side from Shopify
 *   via trusted Admin API, never a browser payload. Caller must enforce this.
 * @param {string} input.verifiedShop - canonical shop linked to the Admin API token.
 * @param {number} input.nowMs
 * @returns {object} Decision only; does not grant commission or execute a postback.
 */
export function assessVerifiedAttribution({
  candidate, verifiedOrder, verifiedShop, nowMs = Date.now(),
}) {
  const reject = reason => ({ status: "rejected", reason, commission_created: false });
  if (!candidate || candidate.status !== "candidate_only" ||
      candidate.requires_order_verification !== true) return reject("invalid_candidate");
  if (typeof verifiedShop !== "string" || !SHOP_RE.test(verifiedShop) ||
      candidate.shop !== verifiedShop) return reject("shop_mismatch");
  const candidateOrderId = normalizeShopifyOrderId(candidate.order_id);
  const actualOrderId = normalizeShopifyOrderId(verifiedOrder?.id);
  if (!candidateOrderId || candidateOrderId !== actualOrderId) return reject("order_mismatch");
  if (typeof candidate.click_id !== "string" || !CLICK_ID_RE.test(candidate.click_id))
    return reject("invalid_click");
  if (!Number.isFinite(nowMs) || !verifiedOrder || typeof verifiedOrder !== "object")
    return reject("unverified_order");
  if (verifiedOrder.cancelled_at || verifiedOrder.closed_at && verifiedOrder.financial_status === "refunded")
    return reject("cancelled_or_refunded");
  if (verifiedOrder.financial_status !== "paid") return reject("payment_not_verified");
  // Shopify order IDs must be independently resolved. The order creation time
  // cannot legitimately be in the future or older than the maximum referral window,
  // but freshness alone is NOT sufficient to prove referral timing.
  const createdMs = Date.parse(verifiedOrder.created_at);
  if (!Number.isFinite(createdMs) || createdMs > nowMs + 60_000)
    return reject("invalid_order_time");
  if (nowMs - createdMs > MAX_WINDOW_MS) return reject("order_too_old_for_prototype");
  return {
    status: "verified_paid_candidate",
    shop: verifiedShop, order_id: candidateOrderId,
    click_id: candidate.click_id,
    commission_created: false,
    // No commission unless separate trusted click validity, consent, eligibility,
    // webhook deduplication, refund-window and payout policies are checked.
    requires_click_validation: true,
    requires_existing_delivery_dedup: true,
    requires_commission_policy: true,
  };
}

/**
 * Fail closed against existing order deliveries. Caller supplies only a
 * TRUSTED DB lookup result for the same shop/order. A missing lookup or
 * query error must NEVER be treated as "no duplicate".
 */
export function assessLegacyDeliveryConflict(verifiedCandidate, deliveryLookup) {
  const reject = reason => ({ status: "blocked", reason, commission_created: false });
  if (verifiedCandidate?.status !== "verified_paid_candidate")
    return reject("not_verified");
  if (!deliveryLookup || deliveryLookup.lookup_ok !== true ||
      deliveryLookup.shop !== verifiedCandidate.shop ||
      normalizeShopifyOrderId(deliveryLookup.order_id) !== verifiedCandidate.order_id)
    return reject("delivery_lookup_unverified");
  if (deliveryLookup.existing_delivery === true)
    return reject("already_in_legacy_delivery_pipeline");
  if (deliveryLookup.existing_delivery !== false)
    return reject("delivery_lookup_ambiguous");
  return { status: "eligible_for_further_review", commission_created: false };
}
